-- One row per lane and day with the number of live cards, feeding the cumulative flow diagram.
create table lane_daily_counts (
    id       bigint generated by default as identity primary key,
    board_id bigint  not null,
    lane_id  bigint  not null,
    snapshot_day date not null,
    cards    integer not null,
    constraint uq_lane_daily_counts unique (lane_id, snapshot_day)
);

create index ix_lane_daily_counts_board on lane_daily_counts (board_id, snapshot_day);
