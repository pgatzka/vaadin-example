-- Flowboard baseline schema. Hibernate validates the entities against it on startup.

create table boards (
    id          bigint generated by default as identity primary key,
    name        varchar(80)                 not null,
    description varchar(500),
    created_at  timestamp(6) with time zone not null
);

create table lanes (
    id         bigint generated by default as identity primary key,
    board_id   bigint      not null,
    name       varchar(60) not null,
    sort_order integer     not null,
    wip_limit  integer,
    done       boolean     not null,
    constraint fk_lanes_board foreign key (board_id) references boards (id)
);

create index ix_lanes_board on lanes (board_id, sort_order);

create table cards (
    id           bigint generated by default as identity primary key,
    lane_id      bigint                      not null,
    title        varchar(120)                not null,
    description  varchar(4000),
    priority     varchar(16)                 not null,
    due_date     date,
    assignee     varchar(60),
    sort_order   integer                     not null,
    created_at   timestamp(6) with time zone not null,
    updated_at   timestamp(6) with time zone not null,
    completed_at timestamp(6) with time zone,
    archived_at  timestamp(6) with time zone,
    constraint fk_cards_lane foreign key (lane_id) references lanes (id)
);

create index ix_cards_lane on cards (lane_id, sort_order);
create index ix_cards_assignee on cards (assignee);

create table card_tags (
    card_id bigint      not null,
    tag     varchar(30) not null,
    primary key (card_id, tag),
    constraint fk_card_tags_card foreign key (card_id) references cards (id)
);

create table checklist_items (
    id         bigint generated by default as identity primary key,
    card_id    bigint       not null,
    text       varchar(200) not null,
    done       boolean      not null,
    sort_order integer      not null,
    constraint fk_checklist_items_card foreign key (card_id) references cards (id)
);

create index ix_checklist_items_card on checklist_items (card_id, sort_order);

create table comments (
    id         bigint generated by default as identity primary key,
    card_id    bigint                      not null,
    author     varchar(60)                 not null,
    text       varchar(2000)               not null,
    created_at timestamp(6) with time zone not null,
    constraint fk_comments_card foreign key (card_id) references cards (id)
);

create index ix_comments_card on comments (card_id, created_at);

create table activities (
    id          bigint generated by default as identity primary key,
    board_id    bigint                      not null,
    card_id     bigint,
    actor       varchar(60)                 not null,
    message     varchar(300)                not null,
    occurred_at timestamp(6) with time zone not null
);

create index ix_activities_board on activities (board_id, occurred_at);
create index ix_activities_card on activities (card_id, occurred_at);
