create table card_watchers (
    id         bigint generated by default as identity primary key,
    card_id    bigint       not null,
    watcher    varchar(60)  not null,
    created_at timestamp(6) not null,
    constraint uk_card_watchers unique (card_id, watcher)
);
create index ix_card_watchers_watcher on card_watchers (watcher);
