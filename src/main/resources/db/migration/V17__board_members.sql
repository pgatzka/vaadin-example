alter table boards add column members_only boolean default false not null;

create table board_members (
    id       bigint generated by default as identity primary key,
    board_id bigint       not null,
    username varchar(40)  not null,
    added_at timestamp(6) not null,
    constraint uk_board_members unique (board_id, username)
);
create index ix_board_members_user on board_members (username);
