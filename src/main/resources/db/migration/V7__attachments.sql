-- Files attached to cards. Metadata and bytes live in separate tables so listing stays cheap.
create table attachments (
    id           bigint generated by default as identity primary key,
    card_id      bigint                      not null,
    file_name    varchar(255)                not null,
    content_type varchar(120)                not null,
    size         bigint                      not null,
    uploaded_by  varchar(60)                 not null,
    uploaded_at  timestamp(6) with time zone not null,
    constraint fk_attachments_card foreign key (card_id) references cards (id)
);

create index ix_attachments_card on attachments (card_id);

create table attachment_data (
    attachment_id bigint primary key,
    data          blob   not null,
    constraint fk_attachment_data_attachment foreign key (attachment_id) references attachments (id) on delete cascade
);
